async def main():
    async with AsyncSessionLocal() as s:
        rows = (await s.execute(
            select(Chunk, Document.filename)
            .join(Document, Chunk.document_id == Document.id)
            .where(Chunk.tenant_id == 'demo', Document.is_active.is_(True))
        )).all()
    by_file = {}
    for c, fname in rows:
        by_file.setdefault(fname, []).append(c)

    def resolve(fname, snippet):
        for c in by_file.get(fname, []):
            if norm(snippet) in norm(c.text):
                return c
        return None

    out, fails = [], []

    def evidence_item(iid, q, refs, points, typ, conversation=None):
        chunks_label = []
        for fname, snippet in refs:
            hit = resolve(fname, snippet)
            if hit is None:
                fails.append((iid, fname, snippet))
                return
            chunks_label.append({"filename": fname, "heading_path": hit.heading_path, "snippet": snippet})
        out.append({
            "id": iid, "query": q, "conversation": conversation,
            "expected_docs": sorted({r[0] for r in refs}),
            "expected_chunks": chunks_label,
            "expected_points": points,
            "has_evidence": True, "type": typ, "safety_tags": [],
        })

    for iid, q, refs, pts in PARAPHRASE:
        evidence_item(iid, q, refs, pts, "paraphrase")
    for iid, q, refs, pts in RARE:
        evidence_item(iid, q, refs, pts, "rare_lexical")
    for iid, q, refs, pts in MULTI_DOC:
        evidence_item(iid, q, refs, pts, "multi_doc")
    for iid, q, conv, refs, pts in MULTI_TURN:
        evidence_item(iid, q, refs, pts, "multi_turn", conversation=conv)

    for iid, q in NO_EVIDENCE:
        out.append({"id": iid, "query": q, "conversation": None,
                    "expected_docs": [], "expected_chunks": [], "expected_points": [],
                    "has_evidence": False, "type": "no_evidence", "safety_tags": []})
    for iid, q, pts in TRAP:
        out.append({"id": iid, "query": q, "conversation": None,
                    "expected_docs": [], "expected_chunks": [], "expected_points": pts,
                    "has_evidence": False, "type": "trap", "safety_tags": []})
    for iid, q, tag in SAFETY:
        out.append({"id": iid, "query": q, "conversation": None,
                    "expected_docs": [], "expected_chunks": [], "expected_points": [],
                    "has_evidence": False, "type": tag, "safety_tags": [tag]})

    print(f'생성 {len(out)}건 / resolve 실패 {len(fails)}건')
    for f in fails:
        c_texts = [c.text[:80].replace("\n", " ") for c in by_file.get(f[1], [])][:0]
        print('  FAIL:', f)
    with open('eval/gold_draft_rest.jsonl', 'w') as fp:
        for o in out:
            fp.write(json.dumps(o, ensure_ascii=False) + '\n')
    print('저장: eval/gold_draft_rest.jsonl')

asyncio.run(main())
