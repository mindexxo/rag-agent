def jobs(n: int, seed: int = 235) -> list[dict]:
    """생성 작업 n개 — 규정 꼴과 다른 도메인을 반씩, (주제×회사) 조합을 돌려가며. id는 r001…/o001…"""
    rnd = random.Random(seed)
    out = []
    for i in range(n):
        if i % 2 == 0:
            k = i // 2
            out.append(
                {
                    'id': f'r{k + 1:04d}',
                    'kind': 'reg',
                    'topic': REG_TOPICS[k % len(REG_TOPICS)],
                    'company': COMPANIES[(k // len(REG_TOPICS)) % len(COMPANIES)],
                    'twist': rnd.sample(TWISTS, 2),
                }
            )
        else:
            k = i // 2
            out.append(
                {
                    'id': f'o{k + 1:04d}',
                    'kind': 'other',
                    'topic': OTHER_TOPICS[k % len(OTHER_TOPICS)],
                    'company': BRANDS[(k // len(OTHER_TOPICS)) % len(BRANDS)],
                    'twist': rnd.sample(TWISTS, 2),
                }
            )
    return out


