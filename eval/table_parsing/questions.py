_DATE_KO = re.compile(r'(\d{4})\s*년\s*(\d{1,2})\s*월\s*(\d{1,2})\s*일')


def _key(s: str) -> str:
    """판정용 정규화 — 날짜 '2026년 11월 5일'→'2026-11-05', 띄어쓰기·쉼표·구두점(·/+)·원·₩ 제거, 소문자."""
    s = _DATE_KO.sub(lambda m: f'{m.group(1)}-{int(m.group(2)):02d}-{int(m.group(3)):02d}', norm(s))
    return re.sub(r'[\s,·/+()]', '', s).replace('원', '').replace('₩', '').lower()


def judge(answer: str, expected: str) -> bool:
    """정답 값이 답변에 들어 있나 — 띄어쓰기·쉼표·원·₩·구두점·한국어 날짜 표기를 무시(OCR 경로가 띄어쓰기를 지우고,
    모델이 날짜를 '2026년 11월 5일'로 바꿔 말하므로 판정에서 뺀다). 말로 바꾼 답("완료된 상태")은 못 잡는다 — manual."""
    return _key(expected) in _key(answer)


