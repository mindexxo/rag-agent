def build_harim() -> Path:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    from eval.table_parsing.build import _BODY, _rl_table   # CID 한글 글꼴 등록도 여기서 된다
    h1 = ParagraphStyle("h1", fontName="HYGothic-Medium", fontSize=16, leading=22, spaceAfter=6)
    h2 = ParagraphStyle("h2", fontName="HYGothic-Medium", fontSize=13, leading=18, spaceBefore=10, spaceAfter=4)
    body = ParagraphStyle("p", parent=_BODY, spaceBefore=4)
    p = OUT / "harim" / "harim_18_협력농가납품단가표.pdf"
    story = [Paragraph("협력 농가 납품 기준 (HR-SCM-018)", h1), Paragraph("별표 1", h2)]   # B4 — 일반 제목
    story += [Paragraph(t, body) for t in HARIM_PREFACE] + [Spacer(1, 4), _rl_table(harim_rows())]
    SimpleDocTemplate(str(p), pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm).build(story)
    return p


def build_homeplus() -> Path:
    from docx import Document as DocxDocument

    from eval.table_parsing.build import _docx_fill
    p = OUT / "homeplus" / "homeplus_18_PB품질검사기준표.docx"
    d = DocxDocument()
    d.add_heading("PB 품질 검사 기준 (HP-QC-018)", level=1)
    d.add_heading("별표 2", level=2)
    d.add_paragraph(HOMEPLUS_PREFACE_LONG)
    rows = homeplus_rows()
    # 머리 두 줄: 첫 행의 '치수 검사'·'중량 검사'는 두 칸 가로 병합, '카테고리'·'품목'은 두 행 세로 병합.
    # 본문 카테고리 칸은 14행씩 세로 병합(B7).
    spec = [[{"t": "카테고리", "rs": 2}, {"t": "품목", "rs": 2}, {"t": "치수 검사", "cs": 2}, None, {"t": "중량 검사", "cs": 2}, None],
            [None, None, "허용 오차", "불합격 시 조치", "허용 오차", "불합격 시 조치"]]
    for i, r in enumerate(rows[2:]):
        first = {"t": r[0], "rs": 14} if i % 14 == 0 else None
        spec.append([first] + r[1:])
    t = d.add_table(rows=len(spec), cols=6)
    t.style = "Table Grid"
    _docx_fill(t, spec)
    d.add_paragraph(HOMEPLUS_FOOTNOTE)
    d.save(p)
    return p


